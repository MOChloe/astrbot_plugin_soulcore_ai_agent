"""Typed storage boundaries used by AI runtime and administration."""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from typing import Any, Protocol


class AIRepositoryPort(Protocol):
    async def create_ai_task(self, profile_id: str, task_type: str, **values: object) -> object: ...
    async def request_pause_ai_task(self, task_id: int, **values: object) -> object: ...
    async def resume_ai_task(self, task_id: int, **values: object) -> object: ...
    async def request_cancel_ai_task(self, task_id: int, **values: object) -> object: ...
    async def manual_retry_ai_task(self, task_id: int, **values: object) -> object: ...
    async def list_ai_manager_pauses(self) -> Sequence[Mapping[str, object]]: ...
    async def list_ai_backends(self) -> Sequence[Mapping[str, object]]: ...
    async def list_ai_api_models(self, **values: object) -> Sequence[Mapping[str, object]]: ...
    async def list_ai_capability_pool(self, capability: str) -> Sequence[Mapping[str, object]]: ...
    async def get_ai_task(self, task_id: int) -> Mapping[str, object] | None: ...
    async def create_ai_workflow(self, record: object) -> Mapping[str, object]: ...
    async def finish_ai_workflow(self, workflow_id: int, **values: object) -> object: ...
    async def start_ai_work_node(self, record: object) -> Mapping[str, object]: ...
    async def project_model_visible_message_ids(
        self,
        run_id: int,
        node_id: int,
        message_ids: Sequence[int],
        *,
        summary_ids: Sequence[int] = (),
        summary_coverage: Sequence[Sequence[int]] = (),
    ) -> object: ...
    async def finish_ai_work_node(self, node_id: int, **values: object) -> object: ...
    async def get_ai_work_node_by_model_invocation(
        self, invocation_id: str
    ) -> Mapping[str, object] | None: ...
    async def start_ai_provider_attempt(self, record: object) -> Mapping[str, object]: ...
    async def enrich_ai_provider_attempt(self, attempt_id: int, **values: object) -> object: ...
    async def mark_ai_provider_attempt_sent(self, attempt_id: int, **values: object) -> object: ...
    async def finish_ai_provider_attempt(self, attempt_id: int, **values: object) -> object: ...
    async def annotate_ai_provider_attempt(self, record: object) -> object: ...
    async def record_ai_work_event(self, record: object) -> object: ...
    async def record_ai_backend_health(self, record: object) -> object: ...
    async def record_ai_circuit_health(self, record: object) -> object: ...
    async def claim_ai_prompt_cache_capability(
        self, backend_id: str, **values: object
    ) -> Mapping[str, object]: ...
    async def observe_ai_prompt_cache_capability(
        self, backend_id: str, **values: object
    ) -> object: ...
    async def reject_ai_prompt_cache_capability(
        self, backend_id: str, **values: object
    ) -> object: ...
    async def request_ai_prompt_cache_reprobe(self, backend_id: str) -> object: ...


