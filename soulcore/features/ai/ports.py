    async def acknowledge_pause_ai_task(self, task_id: int, **values: object) -> object: ...
    async def acknowledge_cancel_ai_task(self, task_id: int, **values: object) -> object: ...
    async def defer_ai_task(self, task_id: int, **values: object) -> object: ...
    async def complete_ai_task(self, task_id: int, **values: object) -> object: ...
    async def fail_ai_task(self, task_id: int, **values: object) -> object: ...
    async def get_ai_task(self, task_id: int) -> Mapping[str, object] | None: ...
    async def record_ai_backend_success(self, backend_id: str) -> object: ...
    async def record_ai_backend_failure(self, backend_id: str, **values: object) -> object: ...
    async def cleanup_ai_task_history(self) -> Mapping[str, object]: ...
    async def create_ai_task(self, profile_id: str, task_type: str, **values: object) -> object: ...
    async def request_pause_ai_task(self, task_id: int, **values: object) -> object: ...
    async def resume_ai_task(self, task_id: int, **values: object) -> object: ...
    async def request_cancel_ai_task(self, task_id: int, **values: object) -> object: ...
    async def manual_retry_ai_task(self, task_id: int, **values: object) -> object: ...


