def creator_publication_contract(
    author_kind: BackgroundAuthorKind,
    *,
    opening_keyframe: bool = False,
) -> str:
    contract = CREATOR_CONTRACTS[author_kind]
    if not opening_keyframe:
        return contract
    return contract.replace("角色现在", "关键帧交接点").replace(
        "这段生活结束时",
        "开篇前史结束、普通生活开始时",
    )


def creator_definition_suffix(author_kind: BackgroundAuthorKind) -> str:
    """Return shared style and the kind-specific bounded writing target."""

    return f"{PUBLICATION_PROSE_STYLE}\n\n{creator_length_instruction(author_kind)}"


def snapshot_repair_contract(*, opening_keyframe: bool = False) -> str:
    """Return the sole model-visible block accepted from a snapshot repair round."""

    contract = _ROLE_CURRENT_CONTRACT
    if not opening_keyframe:
        return contract
    return contract.replace("角色现在", "关键帧交接点").replace(
        "这段生活结束时",
        "开篇前史结束、普通生活开始时",
    )


